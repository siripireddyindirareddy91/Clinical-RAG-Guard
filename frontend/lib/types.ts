export type User = {
  id: string;
  name: string;
  email: string;
  role: string;
  settings: { top_k?: number; max_iterations?: number };
};
export type Source = {
  chunk_id: string;
  document_id: string;
  title: string;
  page: number;
  text: string;
  synthetic: boolean;
  citation: string;
  similarity: number;
  bm25: number;
  fusion: number;
  rerank: number;
  matched_passage?: string;
};
export type Claim = {
  id: string;
  text: string;
  status: string;
  confidence: number;
  explanation: string;
  evidence: Source[];
  action: string;
  citation_valid: boolean;
};
export type Trace = { name: string; status: string; duration_ms: number };
export type Result = {
  id: string;
  question: string;
  answer: string;
  corrected_answer: string;
  claims: Claim[];
  final_claims: Claim[];
  evidence: Source[];
  traces: Trace[];
  corrections: {
    iteration: number;
    original: string;
    corrected: string;
    removed: string[];
    reason: string;
  }[];
  confidence: number;
  coverage: number;
  elapsed_ms: number;
  iteration: number;
  valid: boolean;
  mode: string;
  created_at: string;
  keywords: string[];
};
export type Doc = {
  id: string;
  title: string;
  filename: string;
  category: string;
  source: string;
  author: string;
  publication_year: number | null;
  description: string;
  processing_status: string;
  synthetic: boolean;
  chunk_count: number;
  created_at: string;
};
export type Overview = {
  queries: number;
  documents: number;
  claims: number;
  flagged: number;
  corrected: number;
  confidence: number;
  processing_ms: number;
  distribution: { name: string; value: number }[];
  timeline: { date: string; queries: number; flagged: number }[];
  sources: { name: string; value: number }[];
  recent: Result[];
};
